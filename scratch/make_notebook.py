    "# 3. Módulos de Red Neuronal (RMSNorm, RotaryEmbedding, GQA Self-Attention, MLP SwiGLU)\n",
    "class RMSNorm(nn.Module):\n",
    "    def __init__(self, dim: int, eps: float = 1e-6):\n",
    "        super().__init__()\n",
    "        self.eps = eps\n",
    "        self.weight = nn.Parameter(torch.ones(dim))\n",
    "\n",
    "    def forward(self, x: torch.Tensor) -> torch.Tensor:\n",
    "        variance = x.pow(2).mean(-1, keepdim=True)\n",
    "        return x * torch.rsqrt(variance + self.eps) * self.weight\n",
    "\n",
    "class SwiGLUMLP(nn.Module):\n",
    "    def __init__(self, hidden_size: int, intermediate_size: int):\n",
    "        super().__init__()\n",
    "        self.gate_proj = nn.Linear(hidden_size, intermediate_size, bias=False)\n",
    "        self.up_proj = nn.Linear(hidden_size, intermediate_size, bias=False)\n",
    "        self.down_proj = nn.Linear(intermediate_size, hidden_size, bias=False)\n",
    "\n",
    "    def forward(self, x: torch.Tensor) -> torch.Tensor:\n",
    "        return self.down_proj(nn.functional.silu(self.gate_proj(x)) * self.up_proj(x))\n",
    "\n",
    "class GroupedQueryAttention(nn.Module):\n",
    "    def __init__(self, cfg: RelicConfig):\n",
    "        super().__init__()\n",
    "        self.num_heads = cfg.num_attention_heads\n",
    "        self.num_kv_heads = cfg.num_key_value_heads\n",
    "        self.head_dim = cfg.head_dim\n",
    "        self.num_queries_per_kv = self.num_heads // self.num_kv_heads\n",
    "        self.q_proj = nn.Linear(cfg.hidden_size, self.num_heads * self.head_dim, bias=False)\n",
    "        self.k_proj = nn.Linear(cfg.hidden_size, self.num_kv_heads * self.head_dim, bias=False)\n",
    "        self.v_proj = nn.Linear(cfg.hidden_size, self.num_kv_heads * self.head_dim, bias=False)\n",
    "        self.o_proj = nn.Linear(self.num_heads * self.head_dim, cfg.hidden_size, bias=False)\n",
    "        self.q_norm = RMSNorm(self.head_dim, eps=cfg.rms_norm_eps)\n",
    "        self.k_norm = RMSNorm(self.head_dim, eps=cfg.rms_norm_eps)\n",
    "\n",
    "    def forward(self, x: torch.Tensor) -> torch.Tensor:\n",
    "        B, S, D = x.shape\n",
    "        q = self.q_proj(x).view(B, S, self.num_heads, self.head_dim)\n",
    "        k = self.k_proj(x).view(B, S, self.num_kv_heads, self.head_dim)\n",
    "        v = self.v_proj(x).view(B, S, self.num_kv_heads, self.head_dim)\n",
    "        q = self.q_norm(q)\n",
    "        k = self.k_norm(k)\n",
    "        # Repetir K y V para coincidir con el numero de queries (GQA)\n",
    "        k = k.repeat_interleave(self.num_queries_per_kv, dim=2)\n",
    "        v = v.repeat_interleave(self.num_queries_per_kv, dim=2)\n",
    "        q, k, v = q.transpose(1, 2), k.transpose(1, 2), v.transpose(1, 2)\n",
    "        attn = torch.nn.functional.scaled_dot_product_attention(q, k, v, is_causal=True)\n",
    "        out = attn.transpose(1, 2).contiguous().view(B, S, -1)\n",
    "        return self.o_proj(out)\n",
    "\n",
    "class RelicBlock(nn.Module):\n",
    "    def __init__(self, cfg: RelicConfig):\n",
    "        super().__init__()\n",
    "        self.input_layernorm = RMSNorm(cfg.hidden_size, eps=cfg.rms_norm_eps)\n",
    "        self.self_attn = GroupedQueryAttention(cfg)\n",
    "        self.post_attention_layernorm = RMSNorm(cfg.hidden_size, eps=cfg.rms_norm_eps)\n",
    "        self.mlp = SwiGLUMLP(cfg.hidden_size, cfg.intermediate_size)\n",
    "\n",
    "    def forward(self, x: torch.Tensor) -> torch.Tensor:\n",
    "        h = x + self.self_attn(self.input_layernorm(x))\n",
    "        out = h + self.mlp(self.post_attention_layernorm(h))\n",
    "        return out\n",
    "\n",
    "class RelicForCausalLM(nn.Module):\n",
    "    def __init__(self, cfg: RelicConfig):\n",
    "        super().__init__()\n",
    "        self.config = cfg\n",
    "        self.embed_tokens = nn.Embedding(cfg.vocab_size, cfg.hidden_size)\n",
    "        self.layers = nn.ModuleList([RelicBlock(cfg) for _ in range(cfg.num_hidden_layers)])\n",
    "        self.norm = RMSNorm(cfg.hidden_size, eps=cfg.rms_norm_eps)\n",
    "        self.lm_head = nn.Linear(cfg.hidden_size, cfg.vocab_size, bias=False)\n",
    "\n",
    "    def forward(self, input_ids: torch.Tensor) -> torch.Tensor:\n",
    "        x = self.embed_tokens(input_ids)\n",
    "        for layer in self.layers:\n",
    "            x = layer(x)\n",
    "        x = self.norm(x)\n",
    "        return self.lm_head(x)\n",
    "\n",
    "model = RelicForCausalLM(config)\n",
    "total_params = sum(p.numel() for p in model.parameters())\n",
    "print(f\"Total parámetros inicializados: {total_params:,} (Diseño 10M)\")"
